class I18n {
    constructor() {
        this.locale = localStorage.getItem('tenant_manager_locale') || 'de';
    }

    setLocale(locale) {
        if (translations[locale]) {
            this.locale = locale;
            localStorage.setItem('tenant_manager_locale', locale);
            window.location.reload();
        }
    }

    t(key) {
        return translations[this.locale]?.[key] || key;
    }

    formatCurrency(amount) {
        const val = Number(amount) || 0;
        return new Intl.NumberFormat(this.locale === 'de' ? 'de-DE' : 'en-IE', {
            style: 'currency',
            currency: 'EUR',
            minimumFractionDigits: 2,
            maximumFractionDigits: 2
        }).format(val);
    }

    formatDate(dateString) {
        if (!dateString) return '';
        const date = new Date(dateString);
        if (isNaN(date.getTime())) return dateString;
        return new Intl.DateTimeFormat(this.locale === 'de' ? 'de-DE' : 'en-IE', {
            year: 'numeric',
            month: '2-digit',
            day: '2-digit'
        }).format(date);
    }

    getLocale() {
        return this.locale;
    }
}

export const i18n = new I18n();
export default i18n;
